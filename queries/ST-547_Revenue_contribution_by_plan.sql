WITH user_statistic_by_plan AS (
SELECT
sc.country,
s.plan_name,
COUNT(*) AS users_count,
SUM(s.monthly_fee * (1 - s.discount_percent / 100.0)) AS plan_monthly_revenue 
FROM starlink_customers sc 
JOIN subscriptions s 
ON sc.unique_id = s.customer_id
GROUP BY sc.country, s.plan_name 
),
total_revenue_by_country AS (
SELECT 
sc.country,
SUM(s.monthly_fee * (1 - s.discount_percent / 100.0)) AS country_total_revenue 
FROM starlink_customers sc
JOIN subscriptions s
ON sc.unique_id = s.customer_id
GROUP BY country 
),
comparisson_tariff_by_total_revenue AS (
SELECT *,
((u.plan_monthly_revenue / t.country_total_revenue) * 100.0) AS plan_revenue_share_percent 
FROM user_statistic_by_plan u
INNER JOIN total_revenue_by_country t
ON u.country = t.country 
)
SELECT
country,
plan_name,
users_count,
plan_monthly_revenue,
country_total_revenue,
ROUND(plan_revenue_share_percent,2) AS plan_revenue_share_percent,
RANK() OVER (
PARTITION BY country
ORDER BY plan_monthly_revenue DESC
) AS revenue_rank
FROM comparisson_tariff_by_total_revenue 
WHERE plan_revenue_share_percent >= 30










