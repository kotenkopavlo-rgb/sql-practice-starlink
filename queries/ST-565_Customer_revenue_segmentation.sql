WITH subscription_data AS (
SELECT
s.customer_id,
sc.first_name,
sc.last_name,
s.subscription_id,
s.monthly_fee,
s.discount_percent,
(s.monthly_fee * (1 - (s.discount_percent / 100.0))) AS revenue_after_discount
FROM starlink_customers sc
JOIN subscriptions s
ON sc.unique_id = s.customer_id
),
customer_revenue AS (
SELECT
customer_id,
first_name,
last_name,
COUNT(*) AS subscriptions_count,
SUM(revenue_after_discount ) AS total_revenue,
AVG(revenue_after_discount ) AS avg_revenue
FROM subscription_data
GROUP BY customer_id, first_name, last_name 
),
customer_segmentation AS (
SELECT *,
CASE 
WHEN total_revenue   >= 300 THEN "High Revenue"
WHEN total_revenue   > 100 THEN "Medium Revenue"
ELSE "Low Revenue"
END AS revenue_segment
FROM customer_revenue
)
SELECT
customer_id,
(first_name || ' ' || last_name) AS full_name,
subscriptions_count,
ROUND(total_revenue , 2) AS total_revenue,
ROUND(avg_revenue , 2) AS avg_revenue,
revenue_segment 
FROM customer_segmentation





