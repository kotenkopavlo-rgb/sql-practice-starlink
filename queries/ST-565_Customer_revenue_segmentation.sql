Description:

Calculate the total subscription revenue generated by each
customer and classify customers into revenue segments.

Revenue should be calculated after applying the subscription
discount.

Display:

- Customer ID
- Customer full name
- Number of subscriptions
- Total revenue after discount
- Average revenue per subscription
- Revenue segment

Revenue segments:

- 'Low Revenue'      — total revenue < 100
- 'Medium Revenue'   — total revenue >= 100 and < 300
- 'High Revenue'     — total revenue >= 300

Requirements:

- Join starlink_customers with subscriptions.
- Combine customer's first and last name into a full name.
- Group data by customer.
- Count the number of subscriptions for each customer.
- Calculate total revenue after discount.
- Calculate average revenue per subscription.
- Use CASE to assign each customer to a revenue segment.
- Round revenue values to two decimal places in the final SELECT.
- Include customers who have subscriptions.
- Sort the result by total revenue after discount
  in descending order.

Topics:

- JOIN
- GROUP BY
- COUNT()
- SUM()
- CASE WHEN
- Revenue calculations
- String concatenation
- Aggregation
- Customer segmentation
- Rounding
- ORDER BY

