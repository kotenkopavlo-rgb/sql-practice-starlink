WITH user_statistic AS (
SELECT 
sc.country,
COUNT(*) AS users_count,
SUM(s.monthly_fee * (1 - (s.discount_percent / 100.0))) AS total_monthly_revenue,
AVG(s.monthly_fee * (1 - (s.discount_percent / 100.0))) AS average_revenue_per_user
FROM starlink_customers sc
JOIN subscriptions s 
ON sc.unique_id = s.customer_id
GROUP BY sc.country
),
global_average_calculation AS (
SELECT
AVG((s.monthly_fee * (1 - (s.discount_percent / 100.0)))) AS global_average_revenue_per_user
FROM subscriptions s  
)
SELECT
country,
users_count,
total_monthly_revenue,
ROUND(average_revenue_per_user,2) AS average_revenue_per_user,
ROUND(global_average_revenue_per_user,2) AS global_average_revenue_per_user,
ROUND((average_revenue_per_user - global_average_revenue_per_user),2) AS revenue_difference,
ROUND(((average_revenue_per_user - global_average_revenue_per_user) / global_average_revenue_per_user * 100.0),2) AS revenue_vs_global_percent
FROM user_statistic 
CROSS JOIN global_average_calculation 
WHERE users_count >= 20 AND average_revenue_per_user > global_average_revenue_per_user 
ORDER BY revenue_vs_global_percent DESC



























