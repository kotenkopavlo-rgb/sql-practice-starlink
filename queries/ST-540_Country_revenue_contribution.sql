WITH revenue_per_country AS (
SELECT
sc.country,
COUNT(*) AS users_count,
SUM((s.monthly_fee * (1 - s.discount_percent / 100.0))) AS total_monthly_revenue,
ROUND(AVG((s.monthly_fee * (1 - s.discount_percent / 100.0))),2) AS average_revenue_per_user
FROM starlink_customers sc
JOIN subscriptions s 
ON sc.unique_id = s.customer_id
GROUP BY sc.country
),
total_revenue_by_all_countries AS (
SELECT
SUM((s.monthly_fee * (1 - s.discount_percent / 100.0))) AS global_monthly_revenue
FROM subscriptions s 
)
SELECT
country,
users_count,
total_monthly_revenue,
average_revenue_per_user,
global_monthly_revenue,
ROUND((total_monthly_revenue / global_monthly_revenue) * 100.0,2) AS revenue_share_percentage
FROM revenue_per_country 
CROSS JOIN total_revenue_by_all_countries
WHERE revenue_share_percentage > 10
ORDER BY revenue_share_percentage DESC









