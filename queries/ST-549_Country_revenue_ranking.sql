Description:

Determine which countries are the leaders in revenue
efficiency based on average monthly revenue per user.

For each country calculate:

- country
- users_count
- total_monthly_revenue
- average_revenue_per_user
- country_rank

Monthly revenue for each user should be calculated as:

monthly_fee * (1 - discount_percent / 100.0)

Country metrics:

- users_count — number of users in the country
- total_monthly_revenue — total discounted monthly revenue
  generated by all users in the country
- average_revenue_per_user — average discounted monthly
  revenue per user in the country
- country_rank — ranking of the country based on
  average_revenue_per_user

Include only countries with at least 20 users.

Rank all eligible countries by average_revenue_per_user
in descending order.

Countries with the same average revenue per user should
receive the same rank. The next rank after a tie should
contain a gap.

Example:

1
2
2
4

Use RANK() for calculating the country rank.

Round monetary values to 2 decimal places.

Sort the final result by country_rank in ascending order.

Display:

- country
- users_count
- total_monthly_revenue
- average_revenue_per_user
- country_rank

Topics:

- CTE
- JOIN
