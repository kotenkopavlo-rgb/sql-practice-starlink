WITH statistic_by_country AS (
SELECT 
sc.country,
COUNT(*) AS users_count,
SUM(s.monthly_fee * (1 - (s.discount_percent / 100.0))) AS total_monthly_revenue,
AVG(s.monthly_fee * (1 - (s.discount_percent / 100.0))) AS average_revenue_per_user
FROM starlink_customers sc
JOIN subscriptions s 
ON sc.unique_id = s.customer_id
GROUP BY sc.country 
HAVING COUNT(*) >= 20
),
rank_by_country AS (
SELECT *,
RANK() OVER (
ORDER BY average_revenue_per_user DESC
) AS country_rank 
FROM statistic_by_country 
)
SELECT 
country,
users_count,
total_monthly_revenue,
ROUND(average_revenue_per_user,2) AS average_revenue_per_user,
country_rank
FROM rank_by_country  
ORDER BY country_rank ASC





























